const catalogs: Record<Locale, Record<string, string>> = {
  'en-US': enUS,
  'zh-CN': zhCN,
};

let currentLocale: Locale = getLocaleFromStorageOrDefault();

export function getLocaleFromStorageOrDefault(): Locale {
  if (!browser) {
    return defaultLocale;
  }

  const value = localStorage.getItem(LOCALE_STORAGE_KEY);
  if (value === 'zh-CN') {
    return 'zh-CN';
  }
  return defaultLocale;
}

export function getCurrentLocale(): Locale {
  return currentLocale;
}

export function setCurrentLocale(locale: Locale): void {
  currentLocale = locale;
  if (browser) {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    document.documentElement.lang = locale === 'zh-CN' ? 'zh-CN' : 'en';
  }
}

export function initLocaleFromStorage(): void {
  setCurrentLocale(getLocaleFromStorageOrDefault());
}

export function t(key: string, fallback = ''): string {
  return catalogs[currentLocale]?.[key] || catalogs[defaultLocale][key] || fallback || key;
}

export function tf(key: string, vars?: Record<string, string>, fallback = ''): string {
  let value = t(key, fallback);
  if (!vars) {
    return value;
  }

  for (const [name, val] of Object.entries(vars)) {
    value = value.replaceAll(`{{${name}}}`, val);
  }
  return value;
}

export function getThemeModeFromStorage(): ThemeMode {
  if (!browser) {
    return 'system';
  }

  const value = localStorage.getItem(THEME_STORAGE_KEY);
  if (value === 'light' || value === 'dark' || value === 'system') {
    return value;
  }

  return 'system';
}

export function initThemeFromStorage(): ThemeState {
  return setThemeMode(getThemeModeFromStorage());
}

export function setThemeMode(mode: ThemeMode): ThemeState {
  currentThemeMode = mode;

  if (browser) {
    localStorage.setItem(THEME_STORAGE_KEY, mode);
  }

  const resolved = resolveTheme(mode);

  syncThemeMode(resolved);
  syncSystemThemeListener();

  return {
    mode,
    theme: getThemeNameFromStorage(),
  };
}

export function getCurrentThemeMode(): ThemeMode {
  return currentThemeMode;
}

function syncThemeMode(resolved: 'light' | 'dark'): void {
  if (!browser) {
    return;
  }
  document.documentElement.dataset.theme = getThemeNameFromStorage();
  document.documentElement.dataset.mode = resolved;
}

function syncSystemThemeListener(): void {
  if (!browser) {
    return;
  }

  if (!themeMediaQuery) {
    themeMediaQuery = window.matchMedia(THEME_QUERY);
  }

  if (currentThemeMode === 'system') {
    if (!themeMediaListener) {
      themeMediaListener = () => {
        if (currentThemeMode === 'system') {
          syncThemeMode(resolveTheme('system'));
        }
      };

      if ('addEventListener' in themeMediaQuery) {
        themeMediaQuery.addEventListener('change', themeMediaListener);
      } else {
        // @ts-expect-error legacy fallback
        themeMediaQuery.addListener(themeMediaListener);
      }
    }
    syncThemeMode(resolveTheme('system'));
    return;
  }

  if (themeMediaListener) {
    if ('removeEventListener' in themeMediaQuery) {
      themeMediaQuery.removeEventListener('change', themeMediaListener);
    } else {
      // @ts-expect-error legacy fallback
      themeMediaQuery.removeListener(themeMediaListener);
    }
    themeMediaListener = null;
  }
}

export function resolveTheme(mode: ThemeMode): 'light' | 'dark' {
  if (mode === 'system' && browser) {
    return window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  }

  if (mode === 'dark') {
    return 'dark';
  }

  return 'light';
}

export function getThemeNameFromStorage(): string {
  if (!browser) {
    return 'cerberus';
  }

  return localStorage.getItem(THEME_NAME_STORAGE_KEY) || 'cerberus';
}

export function setThemeName(name: string): void {
  if (!browser) {
    return;
  }

  localStorage.setItem(THEME_NAME_STORAGE_KEY, name);
  document.documentElement.dataset.theme = name;
}
